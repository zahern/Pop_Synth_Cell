#!/usr/bin/env python3
"""Render the before/after pool-support figure for the paper.

Reads ``outputs/pool_before_after_zone.json`` (one zone, per-cell target,
capacity and state before and after expansion) and writes a self-contained
TikZ figure to ``Population_Synthesiser___GAN_SA/files/pool_before_after.tex``.

Each square is one positive-target control cell. The two grids show the zone's
19 control tables before and after expansion; the ledger below lists only the
cells that had no carrier before expansion.
"""
from __future__ import annotations

import argparse
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_JSON = os.path.join(HERE, "outputs", "pool_before_after_zone.json")
DEFAULT_OUT = os.path.normpath(
    os.path.join(HERE, "..", "Population_Synthesiser___GAN_SA", "files",
                 "pool_before_after.tex")
)

CELL = 0.100       # square side, cm
PITCH = 0.145      # horizontal distance between squares, cm
ROW = 0.160        # vertical distance between rows, cm
X0_LEFT = 0.0
X0_RIGHT = 5.15
LEDGER_X = 5.15


def _key(value: str):
    try:
        return (0, int(value))
    except ValueError:
        return (1, str(value))


def _num(value) -> str:
    value = float(value)
    if abs(value - round(value)) < 1e-9:
        return f"{int(round(value)):,}".replace(",", "{,}")
    return f"{value:.1f}"


def _style(state: str) -> str:
    return {"sufficient": "supplied", "short": "short",
            "zero": "zero"}.get(state, "supplied")


def build(doc: dict) -> str:
    zone = str(doc["zone"])
    before = {(r["attr"], r["category"]): r for r in doc["states"]["before"]}
    after = {(r["attr"], r["category"]): r for r in doc["states"]["after"]}
    cells = sorted(set(before) | set(after), key=lambda k: (_key(k[1]), k[0]))
    attrs = sorted({a for a, _ in cells})
    cats = {a: sorted({c for aa, c in cells if aa == a}, key=_key) for a in attrs}
    max_cols = max(len(v) for v in cats.values())
    rows = len(attrs)

    zero_before = sum(1 for r in before.values() if r["state"] == "zero")
    zero_after = sum(1 for r in after.values() if r["state"] == "zero")
    repaired = sum(1 for k, r in before.items()
                   if r["state"] == "zero" and after.get(k, {}).get("state") == "sufficient")
    n_cells = len(before)
    pool = doc.get("pool_stats", {})
    p0 = pool.get("before", {})
    p1 = pool.get("after", {})

    def grid(x0: float, source: dict, want_after: bool) -> list[str]:
        out = []
        for i, attr in enumerate(attrs):
            y = (rows - 1 - i) * ROW
            out.append(
                "\\node[poolrow, anchor=east] at (%.3f,%.3f) {\\texttt{%s}};"
                % (x0 - 0.10, y, attr)
            )
            for j, cat in enumerate(cats[attr]):
                x = x0 + j * PITCH
                rec = source.get((attr, cat), {})
                state = rec.get("state", "sufficient")
                if want_after and before.get((attr, cat), {}).get("state") == "zero" \
                        and state == "sufficient":
                    style = "repaired"
                else:
                    style = _style(state)
                out.append(f"\\node[{style}] at ({x:.3f},{y:.3f}) {{}};")
        return out

    lines: list[str] = []
    lines.append("% Generated by make_pool_before_after_fig.py -- do not edit by hand.")
    lines.append(f"% Source: outputs/pool_before_after_zone.json (zone {zone}).")
    lines.append("\\begin{figure}[t]")
    lines.append("\\centering")
    lines.append("\\resizebox{\\linewidth}{!}{%")
    lines.append("\\begin{tikzpicture}[")
    lines.append("  poolcell/.style={draw=black!35, line width=0.2pt,")
    lines.append("    minimum width=%.3fcm, minimum height=%.3fcm, inner sep=0pt}," % (CELL, CELL))
    lines.append("  supplied/.style={poolcell, fill=blue!22, draw=blue!55!black},")
    lines.append("  short/.style={poolcell, fill=orange!45, draw=orange!70!black},")
    lines.append("  zero/.style={poolcell, fill=red!62, draw=red!72!black},")
    lines.append("  repaired/.style={poolcell, fill=green!48!black, draw=green!38!black},")
    lines.append("  poolrow/.style={font=\\tiny, inner sep=1pt},")
    lines.append("  head/.style={font=\\scriptsize\\bfseries, anchor=south west, inner sep=0pt},")
    lines.append("  note/.style={font=\\scriptsize, align=left, inner sep=0pt},")
    lines.append("  led/.style={font=\\tiny, anchor=west, inner sep=1pt},")
    lines.append("]")
    lines.append("")

    # Panel titles
    lines.append(f"\\node[head] at ({X0_LEFT - 1.28:.3f},{rows * ROW + 0.02:.3f}) "
                 "{(a) before expansion};")
    lines.append(f"\\node[head] at ({X0_RIGHT - 1.28:.3f},{rows * ROW + 0.02:.3f}) "
                 "{(b) after expansion};")

    lines.extend(grid(X0_LEFT, before, want_after=False))
    lines.extend(grid(X0_RIGHT, after, want_after=True))
    lines.append("")

    # Horizontal rule under the grids
    lines.append(f"\\draw[black!20, line width=0.4pt] ({X0_LEFT - 1.30:.3f},-0.16) "
                 f"-- ({X0_RIGHT + max_cols * PITCH + 0.10:.3f},-0.16);")

    # Legend
    ly = -0.32
    lines.append(f"\\node[supplied] at ({X0_LEFT - 1.18:.3f},{ly:.3f}) {{}};")
    lines.append(f"\\node[led] at ({X0_LEFT - 1.04:.3f},{ly:.3f}) {{supplied}};")
    lines.append(f"\\node[zero] at ({X0_LEFT + 0.05:.3f},{ly:.3f}) {{}};")
    lines.append(f"\\node[led] at ({X0_LEFT + 0.20:.3f},{ly:.3f}) {{zero capacity}};")
    lines.append(f"\\node[repaired] at ({X0_LEFT + 1.90:.3f},{ly:.3f}) {{}};")
    lines.append(f"\\node[led] at ({X0_LEFT + 2.05:.3f},{ly:.3f}) {{repaired}};")

    # Summary
    summary = (
        f"\\textbf{{Zero-capacity cells:}} {zero_before} before, {zero_after} "
        f"\\mbox{{after}} (\\mbox{{{repaired} repaired}}). "
        f"\\textbf{{Remaining:}} \\texttt{{qalfp:16}}, a structural code with no "
        f"resident donor. "
    )
    if p0 and p1:
        dp = p1["persons"] - p0["persons"]
        dh = p1["households"] - p0["households"]
        pct = 100.0 * dp / p0["persons"] if p0["persons"] else 0.0
        summary += (
            f"\\textbf{{Zone pool slice:}} {_num(p0['persons'])} $\\rightarrow$ "
            f"{_num(p1['persons'])} persons (+{_num(dp)}, {pct:.1f}\\%), "
            f"{_num(p0['households'])} $\\rightarrow$ {_num(p1['households'])} "
            f"households (+{_num(dh)})."
        )
    lines.append(f"\\node[note, anchor=north west, text width=5.75cm] "
                 f"at ({X0_LEFT - 1.30:.3f},-0.52) {{{summary}}};")

    # Ledger of cells that were zero before expansion
    deficit = sorted(
        (k for k in cells if before.get(k, {}).get("state") == "zero"),
        key=lambda k: (attrs.index(k[0]), _key(k[1])),
    )
    lines.append(f"\\node[font=\\scriptsize\\bfseries, anchor=west, inner sep=0pt] "
                 f"at ({LEDGER_X:.3f},-0.32) {{cells with no carrier before expansion}};")
    lines.append(f"\\node[led, font=\\tiny\\bfseries] at ({LEDGER_X + 0.18:.3f},-0.53) {{cell}};")
    lines.append(f"\\node[led, font=\\tiny\\bfseries] at ({LEDGER_X + 1.58:.3f},-0.53) "
                 "{target $\\rightarrow$ capacity};")
    y = -0.74
    for k in deficit:
        attr, cat = k
        rec = after.get(k, {})
        cap = rec.get("capacity", 0.0)
        target = rec.get("target", before.get(k, {}).get("target", 0.0))
        style = "zero" if rec.get("state") == "zero" else "repaired"
        lines.append(f"\\node[{style}] at ({LEDGER_X:.3f},{y:.3f}) {{}};")
        lines.append(f"\\node[led] at ({LEDGER_X + 0.18:.3f},{y:.3f}) "
                     f"{{\\texttt{{{attr}:{cat}}}}};")
        lines.append(f"\\node[led] at ({LEDGER_X + 1.58:.3f},{y:.3f}) "
                     f"{{{_num(target)} $\\rightarrow$ {_num(cap)}}};")
        y -= 0.185

    lines.append("")
    lines.append("\\end{tikzpicture}%")
    lines.append("}")
    lines.append(
        "\\caption{Pool support before and after expansion for zone %s, the worked "
        "example used in the audit. Each square is one positive-target control cell "
        "in the zone's %d control tables; rows are tables and columns are the cells "
        "present in that table. Blue cells already supply at least the carrier "
        "capacity the fitter needs, red cells supply nothing, and green cells were "
        "red before expansion and are supplied after it. The zone's slice grows by "
        "only %s persons (%.1f\\%%) and %s households, but the number of unreachable "
        "target cells falls from %d to %d; the cell that remains is the structural "
        "code \\texttt{qalfp:16}, for which the extract has no resident donor.}"
        % (zone, len(attrs), _num((pool.get("after", {}).get("persons", 0)
                                   - pool.get("before", {}).get("persons", 0))),
           100.0 * (pool.get("after", {}).get("persons", 0)
                    - pool.get("before", {}).get("persons", 0))
           / pool.get("before", {}).get("persons", 1),
           _num(pool.get("after", {}).get("households", 0)
                - pool.get("before", {}).get("households", 0)),
           zero_before, zero_after)
    )
    lines.append("\\label{fig:pool_before_after}")
    lines.append("\\end{figure}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", default=DEFAULT_JSON)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()
    with open(args.json) as fh:
        doc = json.load(fh)
    text = build(doc)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write(text)
    print(f"wrote {args.out}  ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
